import "server-only";
import type Docker from "dockerode";
import { z } from "zod";
import { DomainError } from "@/lib/domain/errors";
import { parseInput } from "@/lib/validation/parse";
import { subnetCidrSchema } from "@/lib/validation/schemas";
import { LABEL_DEVICE_ID, LABEL_FACTORY_ID, LABEL_MANAGED, LABEL_SERVICE } from "./labels";
import type { RuntimeImage, RuntimePolicy } from "./policy";
import type { PortBinding } from "./ports";

/**
 * Builds Docker create options from validated requests. The request schemas are strict:
 * a key that is not listed (privileged, binds, volumes, cmd, entrypoint, capAdd, network
 * mode, devices…) is rejected, so an option outside the allow-list cannot reach Docker.
 * Everything security-relevant in the output is fixed here, not taken from the request.
 */

/** Factory network names are generated by the application: `zfactory_<id>`. */
const NETWORK_NAME = /^zfactory_[a-z0-9][a-z0-9_.-]{0,62}$/;
/** Service names double as DNS names inside the factory network. */
const DNS_LABEL = /^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/;

const port = z.number().int().min(1).max(65535);

export const networkRequestSchema = z.strictObject({
  factoryId: z.uuid(),
  name: z.string().regex(NETWORK_NAME, "Network names must look like zfactory_<id>."),
  subnetCidr: subnetCidrSchema,
});
export type NetworkRequest = z.infer<typeof networkRequestSchema>;

export const containerRequestSchema = z.strictObject({
  factoryId: z.uuid(),
  /** Z-Factory device instance the container runs for. */
  deviceId: z.uuid(),
  networkName: z.string().regex(NETWORK_NAME, "Network names must look like zfactory_<id>."),
  serviceName: z.string().regex(DNS_LABEL, "Use lowercase letters, digits and hyphens."),
  /** Key of an allow-listed runtime image. */
  image: z.string().min(1),
  env: z.record(z.string(), z.string().max(4096)).default({}),
  ports: z
    .array(z.strictObject({ containerPort: port, hostPort: port, bindAddress: z.string().optional() }))
    .max(16)
    .default([]),
  limits: z
    .strictObject({ cpus: z.number().positive().optional(), memoryMb: z.number().int().positive().optional() })
    .default({}),
});
export type ContainerRequest = z.infer<typeof containerRequestSchema>;

export type ContainerSpec = {
  image: RuntimeImage;
  ports: PortBinding[];
  options: Docker.ContainerCreateOptions;
};

function managedLabels(policy: RuntimePolicy, labels: Record<string, string>): Record<string, string> {
  return { ...policy.labels, ...labels, [LABEL_MANAGED]: "true" };
}

export function buildNetworkCreateOptions(input: unknown, policy: RuntimePolicy): Docker.NetworkCreateOptions {
  const request = parseInput(networkRequestSchema, input);
  return {
    Name: request.name,
    Driver: "bridge",
    CheckDuplicate: true,
    Internal: false,
    Attachable: false,
    EnableIPv6: false,
    IPAM: { Driver: "default", Config: [{ Subnet: request.subnetCidr }] },
    Labels: managedLabels(policy, { [LABEL_FACTORY_ID]: request.factoryId }),
  };
}

function resolveImage(key: string, policy: RuntimePolicy): RuntimeImage {
  const image = policy.images.find((candidate) => candidate.key === key);
  if (!image) {
    throw new DomainError("VALIDATION", "This runtime image is not on the allow-list.", { rule: "image-allow-list" });
  }
  return image;
}

function resolveEnv(env: Record<string, string>, image: RuntimeImage): string[] {
  return Object.entries(env).map(([name, value]) => {
    if (!image.allowedEnv.includes(name)) {
      throw new DomainError("VALIDATION", `Environment variable ${name} is not allowed for this image.`, {
        rule: "env-allow-list",
      });
    }
    // A newline or NUL would let a value smuggle a second variable.
    if (/[\0\r\n]/.test(value)) {
      throw new DomainError("VALIDATION", `Environment variable ${name} contains control characters.`, {
        rule: "env-value",
      });
    }
    return `${name}=${value}`;
  });
}

function resolveLimits(limits: ContainerRequest["limits"], policy: RuntimePolicy) {
  const cpus = limits.cpus ?? policy.limits.defaultCpus;
  const memoryMb = limits.memoryMb ?? policy.limits.defaultMemoryMb;
  if (cpus > policy.limits.maxCpus) {
    throw new DomainError("VALIDATION", `CPU limit cannot exceed ${policy.limits.maxCpus}.`, { rule: "cpu-limit" });
  }
  if (memoryMb > policy.limits.maxMemoryMb || memoryMb < 16) {
    throw new DomainError("VALIDATION", `Memory limit must be between 16 and ${policy.limits.maxMemoryMb} MB.`, {
      rule: "memory-limit",
    });
  }
  return { nanoCpus: Math.round(cpus * 1e9), memoryBytes: memoryMb * 1024 * 1024 };
}

export function containerNameFor(factoryId: string, serviceName: string): string {
  return `zf-${factoryId}-${serviceName}`;
}

export function buildContainerSpec(input: unknown, policy: RuntimePolicy): ContainerSpec {
  const request = parseInput(containerRequestSchema, input);
  const image = resolveImage(request.image, policy);
  const { nanoCpus, memoryBytes } = resolveLimits(request.limits, policy);

  const defaultBindAddress = policy.bindAddresses[0] ?? "127.0.0.1";
  const ports = request.ports.map((binding) => ({
    containerPort: binding.containerPort,
    hostPort: binding.hostPort,
    bindAddress: binding.bindAddress ?? defaultBindAddress,
  }));
  for (const binding of ports) {
    if (!image.publishablePorts.includes(binding.containerPort)) {
      throw new DomainError("VALIDATION", `Container port ${binding.containerPort} cannot be published.`, {
        rule: "publishable-port",
      });
    }
  }

  const exposedPorts: Record<string, object> = {};
  const portBindings: Record<string, Array<{ HostIp: string; HostPort: string }>> = {};
  for (const binding of ports) {
    const key = `${binding.containerPort}/tcp`;
    exposedPorts[key] = {};
    (portBindings[key] ??= []).push({ HostIp: binding.bindAddress, HostPort: String(binding.hostPort) });
  }

  const options: Docker.ContainerCreateOptions = {
    name: containerNameFor(request.factoryId, request.serviceName),
    Image: image.digest ? `${image.reference}@${image.digest}` : image.reference,
    Hostname: request.serviceName,
    // Only the allow-list decides what runs; the image's own entrypoint is kept.
    Cmd: image.command ? [...image.command] : undefined,
    Env: resolveEnv(request.env, image),
    ExposedPorts: exposedPorts,
    Labels: managedLabels(policy, {
      [LABEL_FACTORY_ID]: request.factoryId,
      [LABEL_DEVICE_ID]: request.deviceId,
      [LABEL_SERVICE]: request.serviceName,
    }),
    HostConfig: {
      // One isolated network per factory; never the host network.
      NetworkMode: request.networkName,
      PortBindings: portBindings,
      Privileged: false,
      CapDrop: ["ALL"],
      SecurityOpt: ["no-new-privileges"],
      // No host paths, volumes or devices ever enter a runtime container.
      Binds: [],
      Mounts: [],
      Devices: [],
      NanoCpus: nanoCpus,
      Memory: memoryBytes,
      MemorySwap: memoryBytes,
      PidsLimit: policy.limits.pidsLimit,
      RestartPolicy: { Name: "no" },
      AutoRemove: false,
      Init: true,
      LogConfig: { Type: "json-file", Config: { "max-size": "10m", "max-file": "3" } },
    },
    NetworkingConfig: { EndpointsConfig: { [request.networkName]: { Aliases: [request.serviceName] } } },
  };

  return { image, ports, options };
}
